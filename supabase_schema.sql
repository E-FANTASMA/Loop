CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email text NOT NULL UNIQUE,
    display_name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
BEGIN
    INSERT INTO public.profiles (id, email, display_name)
    VALUES (
        NEW.id,
        lower(NEW.email),
        coalesce(
            nullif(trim(NEW.raw_user_meta_data ->> 'display_name'), ''),
            split_part(NEW.email, '@', 1)
        )
    )
    ON CONFLICT (id) DO UPDATE
    SET email = EXCLUDED.email,
        display_name = EXCLUDED.display_name;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();

CREATE TABLE IF NOT EXISTS public.listings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text NOT NULL DEFAULT '',
    category text NOT NULL,
    price bigint NOT NULL CHECK (price >= 0),
    condition text NOT NULL,
    location text NOT NULL,
    seller_name text NOT NULL,
    phone text NOT NULL DEFAULT '',
    icon text NOT NULL DEFAULT '◇',
    created_at timestamptz NOT NULL DEFAULT now(),
    owner_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
    image_name text,
    status text NOT NULL DEFAULT 'active',
    listing_type text NOT NULL DEFAULT 'sale',
    swap_for text NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS listings_status_created_idx
    ON public.listings (status, created_at DESC);
CREATE INDEX IF NOT EXISTS listings_owner_idx
    ON public.listings (owner_id);

CREATE TABLE IF NOT EXISTS public.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
    sender_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    recipient_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz
);
CREATE INDEX IF NOT EXISTS messages_listing_created_idx
    ON public.messages (listing_id, created_at, id);
CREATE INDEX IF NOT EXISTS messages_participants_idx
    ON public.messages (sender_id, recipient_id);

CREATE TABLE IF NOT EXISTS public.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES public.listings(id) ON DELETE RESTRICT,
    buyer_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
    seller_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
    amount bigint NOT NULL CHECK (amount >= 0),
    status text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_buyer_idx ON public.orders (buyer_id, id DESC);
CREATE INDEX IF NOT EXISTS orders_seller_idx ON public.orders (seller_id, id DESC);

CREATE TABLE IF NOT EXISTS public.reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
    reporter_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    reason text NOT NULL,
    details text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'open',
    created_at timestamptz NOT NULL DEFAULT now(),
    reviewed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    UNIQUE (listing_id, reporter_id)
);
CREATE INDEX IF NOT EXISTS reports_status_idx ON public.reports (status, id);

